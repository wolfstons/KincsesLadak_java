package modell;

public class Lada {
    private String nev;
    private String allitas;

    public Lada(String nev, String allitas) {
        this.nev = nev;
        this.allitas = allitas;
    }

    public String getNev() {
        return nev;
    }

    public String getAllitas() {
        return allitas;
    }
}
